import assert from 'node:assert/strict';
import './dist/usage-rules.js';
const R=globalThis.MobUsageRules;
const base={id:'one',enabled:true,mode:'daily',minutes:2,items:[{kind:'website',label:'example.com'},{kind:'app',label:'editor'}]};
const rule=R.clean([base])[0];
assert(R.blocked(rule,{daily:{'website:example.com':60,'app:editor':60}}));
assert(!R.blocked(rule,{daily:{'website:other.com':3600,'app:editor':60}}));
assert(R.blocked(rule,{daily:{'website:sub.example.com':120}}));
assert(!R.blocked({...rule,enabled:false},{daily:{'app:editor':600}}));
assert(R.blocked({...rule,mode:'focus'},{now:100,focusUntil:200}));
assert(!R.blocked({...rule,mode:'focus'},{now:200,focusUntil:200}));
const schedule={...rule,mode:'schedule',days:[1],start:'22:00',end:'02:00'};
assert(R.blocked(schedule,{now:new Date(2026,10,16,23).getTime()}));
assert(R.blocked(schedule,{now:new Date(2026,10,17,1).getTime()}));
assert(!R.blocked(schedule,{now:new Date(2026,10,17,3).getTime()}));
let sessions=R.advance([{...rule,mode:'session'}],{},'app','editor',60,100000);
sessions=R.advance([{...rule,mode:'session'}],sessions,'website','sub.example.com',60,130000);
assert.equal(sessions.one.seconds,120);
assert(R.blocked({...rule,mode:'session'},{session:sessions.one.seconds}));
sessions=R.advance([{...rule,mode:'session'}],sessions,'app','other',0,200001);
assert.equal(sessions.one.seconds,0);
assert.equal(R.clean([{...base,items:[{kind:'website',label:'*'}]}]).length,0);
console.log('Selective rules passed: mixed daily totals, subdomains, schedules overnight, focus boundaries, session continuity/reset and invalid domains.');
